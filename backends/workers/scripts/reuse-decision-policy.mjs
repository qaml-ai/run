import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../../../src/', import.meta.url);
const output = new URL('../src/', import.meta.url);
const header = '// Generated by scripts/reuse-decision-policy.mjs from src/. Only host imports/types change.\n';
const replacements = {
  'multi-agent.ts': [
    ['"./http.ts"', '"./errors.ts"'],
    ['"./sender.ts"', '"./sender-markers.ts"'],
    ['"./protocol.ts"', '"./policy-host.ts"'],
    ['"./core/computer-fork.ts"', '"../../../src/core/computer-fork.ts"'],
  ],
  'decisions.ts': [
    ['"./client-sessions/state.ts"', '"./policy-host.ts"'],
    ['"./identity.ts"', '"./policy-host.ts"'],
    ['"./mcp-results.ts"', '"./policy-host.ts"'],
    ['"./protocol.ts"', '"./policy-host.ts"'],
    ['"./http.ts"', '"./policy-host.ts"'],
    ['"./limits.ts"', '"../../../src/limits.ts"'],
    ['"./metrics.ts"', '"./policy-host.ts"'],
    // The questions' shapes and checks are shared core code (src/core), imported where they are.
    ['"./core/decision-questions.ts"', '"../../../src/core/decision-questions.ts"'],
  ],
  'decision-providers.ts': [
    ['"./outbound.ts"', '"./policy-host.ts"'],
    ['"./decisions.ts"', '"./decision-policy.ts"'],
    ['"./limits.ts"', '"../../../src/limits.ts"'],
    ['"./metrics.ts"', '"./policy-host.ts"'],
  ],
};
for (const [name, edits] of Object.entries(replacements)) {
  let text = await readFile(new URL(name, source), 'utf8');
  for (const [before, after] of edits) text = text.replaceAll(before, after);
  text = header + text;
  const target = new URL(name === 'multi-agent.ts' ? 'multi-agent-policy.ts' : name === 'decisions.ts' ? 'decision-policy.ts' : name, output);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== text) throw new Error(`${name} policy drifted`);
  } else await writeFile(target, text);
}
const sender = await readFile(new URL('sender.ts', source), 'utf8');
const markers = (header + sender.slice(sender.indexOf('export const CONTEXT_OPEN'), sender.indexOf('/** A sender from a request:'))).trimEnd() + '\n';
const markerPath = new URL('sender-markers.ts', output);
if (process.argv.includes('--check')) {
  if (await readFile(markerPath, 'utf8') !== markers) throw new Error('sender markers drifted');
} else await writeFile(markerPath, markers);
const portableSender = header + sender.replace('import type { AgentMessage } from "@earendil-works/pi-agent-core";', 'import type { Message as AgentMessage } from "@earendil-works/pi-ai";').replace('"./http-error.ts"', '"./errors.ts"');
const senderPath = new URL('sender.ts', output);
if (process.argv.includes('--check')) {
  if (await readFile(senderPath, 'utf8') !== portableSender) throw new Error('sender policy drifted');
} else await writeFile(senderPath, portableSender);
const spend = await readFile(new URL('client-sessions/spend.ts', source), 'utf8');
const children = await readFile(new URL('client-sessions/delegation.ts', source), 'utf8');
const childPolicy = header + `export type DelegateResponse = { run: string; messageIndex: number; taken: number };
export type Session = { childHeld?: Map<string, { usd: number; holders: number }>; delegateResponse?: DelegateResponse; delegating?: { active: number } };
type SpendContext = { left?: number };
const budgetLeft = async (ctx: SpendContext, _session: Session, _run: string) => ctx.left;
type Mount = { volumeId: string; path: string; mode: 'ro' | 'rw'; subpath?: string; notify?: boolean; instructions?: string };
` + spend.slice(spend.indexOf('/**\n * The spend limit a delegate'), spend.indexOf('/**\n * A background child\'s spend')) +
  children.slice(children.indexOf('/**\n * What a child of the model\'s own'), children.indexOf('/** A child\'s prompt:'));
const childPath = new URL('delegation-policy.ts', output);
if (process.argv.includes('--check')) {
  if (await readFile(childPath, 'utf8') !== childPolicy) throw new Error('child policy drifted');
} else await writeFile(childPath, childPolicy);
console.log('Decision and multi-agent policy matches src/');
