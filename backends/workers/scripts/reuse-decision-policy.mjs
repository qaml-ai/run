import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../../../src/', import.meta.url);
const output = new URL('../src/', import.meta.url);
const header = '// Generated by scripts/reuse-decision-policy.mjs from src/. Only host imports/types change.\n';
const replacements = {
  'multi-agent.ts': [
    ['"./http.ts"', '"./errors.ts"'],
    ['"./sender.ts"', '"./sender-markers.ts"'],
    ['"./protocol.ts"', '"./policy-host.ts"'],
  ],
  'decisions.ts': [
    ['"./client-sessions/state.ts"', '"./policy-host.ts"'],
    ['"./identity.ts"', '"./policy-host.ts"'],
    ['"./mcp-results.ts"', '"./policy-host.ts"'],
    ['"./protocol.ts"', '"./policy-host.ts"'],
    ['"./http.ts"', '"./policy-host.ts"'],
    ['"./limits.ts"', '"../../../src/limits.ts"'],
    ['"./metrics.ts"', '"./policy-host.ts"'],
  ],
  'decision-providers.ts': [
    ['"./outbound.ts"', '"./policy-host.ts"'],
    ['"./decisions.ts"', '"./decision-policy.ts"'],
    ['"./limits.ts"', '"../../../src/limits.ts"'],
    ['"./metrics.ts"', '"./policy-host.ts"'],
  ],
};
for (const [name, edits] of Object.entries(replacements)) {
  let text = await readFile(new URL(name, source), 'utf8');
  for (const [before, after] of edits) text = text.replaceAll(before, after);
  text = header + text;
  const target = new URL(name === 'multi-agent.ts' ? 'multi-agent-policy.ts' : name === 'decisions.ts' ? 'decision-policy.ts' : name, output);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== text) throw new Error(`${name} policy drifted`);
  } else await writeFile(target, text);
}
const sender = await readFile(new URL('sender.ts', source), 'utf8');
const markers = header + sender.slice(sender.indexOf('export const CONTEXT_OPEN'), sender.indexOf('/** A sender from a request:'));
const markerPath = new URL('sender-markers.ts', output);
if (process.argv.includes('--check')) {
  if (await readFile(markerPath, 'utf8') !== markers) throw new Error('sender markers drifted');
} else await writeFile(markerPath, markers);
console.log('Decision and multi-agent policy matches src/');
