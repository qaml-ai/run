import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../../../src/workflows.ts', import.meta.url), 'utf8');
const generated = '// Generated by scripts/reuse-workflow.mjs from src/workflows.ts. Do not edit.\n' +
  'import { HttpError } from "./errors.ts";\nimport type { ToolDefinition } from "./policy-host.ts";\nimport { MULTI_AGENT_LIMITS, targetsInput, type AgentTarget } from "./multi-agent-policy.ts";\n\n' +
  source.slice(source.indexOf('export const WORKFLOW_LIMITS'), source.indexOf('export type ScriptRunOptions')) +
  source.slice(source.indexOf('function fnv1a('), source.indexOf('const WORKFLOW_TOOL')).replace('function fnv1a(', 'export function fnv1a(') +
  source.slice(source.indexOf('function scriptCode('), source.indexOf('/**\n * Run a workflow script')).replace('function scriptCode(', 'export function scriptCode(') +
  source.slice(source.indexOf('/** Keep child metadata'));
const target = new URL('../src/workflow-policy.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== generated) throw new Error('Workflow policy drifted from src/');
} else await writeFile(target, generated);
console.log('Workflow policy matches src/');
