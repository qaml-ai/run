import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../../../', import.meta.url);
const source = async path => readFile(new URL(path, root), 'utf8');
const protocol = await source('src/protocol.ts');
const outputs = new Map();
const banner = '// Generated by scripts/reuse-model-policy.mjs from the ECS runtime. Do not edit.\n';
outputs.set('model-catalog.ts', banner + await source('src/pi-catalog.ts'));
const session = await source('src/session-config.ts');
const virtual = (await source('src/virtual-models.ts')).replace(/import[^\n]+\n/g, '');
const pass = await source('src/openrouter-model.ts');
const catalog = await source('src/catalog.ts');
outputs.set('model-policy.ts', banner + `import type { Api, Model } from '@earendil-works/pi-ai';
import { getModel, temperatureRefusal } from './model-catalog.ts';
import { deepseekOnOpenRouter } from './deepseek-policy.ts';
import { HttpError } from './errors.ts';
export type RunLimits = { maxResponses?: number; maxSeconds?: number; firstTokenSeconds?: number; idleSeconds?: number; contextTokens?: number };
type AgentConfig = { model: Model<Api>; thinkingLevel?: string; maxOutputTokens?: number | null; temperature?: number | null };
const MIN_CONTEXT_TOKENS = ${protocol.match(/export const MIN_CONTEXT_TOKENS = ([^;]+);/)[1]};
` + catalog.slice(catalog.indexOf('export function openRouterApi('), catalog.indexOf('export const modelInfo')) +
pass.slice(pass.indexOf('const DEFAULTS ='), pass.indexOf('type Endpoint =')) + virtual +
session.slice(session.indexOf('/** What a model on a tenant'), session.indexOf('/**\n * A tenant\'s own model endpoint')) +
session.slice(session.indexOf('export type ModelEndpoint ='), session.indexOf('/**\n * The providers an endpoint')) +
session.slice(session.indexOf('export const UPSTREAMS'), session.indexOf('/**\n * Resolve a model reference')) +
session.slice(session.indexOf('export function resolveModel'), session.indexOf('export function configurationRefusal')));
const history = await source('src/history.ts');
outputs.set('history-policy.ts', banner + `import type { Message } from '@earendil-works/pi-ai';
type AgentMessage = Message | { role: 'compactionSummary'; summary: string; [key: string]: unknown };
const validFileRef = (part: Record<string, unknown>) => part.type === 'file' && typeof part.path === 'string';
` + history.slice(history.indexOf('/** An imported compaction'), history.indexOf('export function validateUserMessages')));
outputs.set('deepseek-policy.ts', banner + await source('src/deepseek-replay.ts'));
outputs.set('history-formats.ts', banner + (await source('clients/history-formats.ts')).replace('import type { Message } from \"./types.ts\";', 'import type { Message } from \"@earendil-works/pi-ai\";'));
const prompt = await source('src/system-prompt.ts');
outputs.set('output-policy.ts', banner + await source('src/tool-choice.ts') + '\n' + prompt.slice(prompt.indexOf('export const OUTPUT_TOOL'), prompt.indexOf('export function applicationInstructions')));
for (const [name, text] of outputs) {
 const path = new URL('../src/' + name, import.meta.url);
 if (process.argv.includes('--check')) { if (await readFile(path, 'utf8') !== text) throw new Error(name + ' has source drift'); }
 else await writeFile(path, text);
}
console.log('Agent model and history policy match src/');
