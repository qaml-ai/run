import { readFile, writeFile } from "node:fs/promises";
const source = await readFile(new URL("../../../src/openapi.ts", import.meta.url), "utf8");
const between = (start, end) => {
  const from = source.indexOf(start), to = source.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error("OpenAPI extraction boundary changed");
  return source.slice(from, to);
};
const text = `// Generated by scripts/reuse-openapi.mjs from src/openapi.ts. Do not edit.\n` +
  between("export type Parameter", "/** A spec's text") +
  between("export function checkDocument", "/** An operation as the agent sees it") +
  between("export function formEncode", "/**\n * A response as an MCP result");
const destination = new URL("../src/openapi-policy.ts", import.meta.url);
const normalized = text.trimEnd() + "\n";
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== normalized) throw new Error("OpenAPI policy drifted; regenerate");
} else await writeFile(destination, normalized);
console.log("OpenAPI operation policy matches src/openapi.ts");
