import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../../../', import.meta.url);
const target = new URL('../src/media/', import.meta.url);
await mkdir(target, { recursive: true });
for (const name of ['images.ts', 'transcription.ts', 'speech.ts', 'speech-api.ts', 'voice-providers/tts.ts', 'voice-providers/tts-chain.ts']) {
  let source = await readFile(new URL('src/' + name, root), 'utf8');
  const depth = name.includes('/') ? '../' : '';
  // Only host imports change. Provider requests, validation, pricing and streams are maintained in src/.
  source = source.replace(/(from )(["'])(\.[^"']+)\2/g, (match, prefix, quote, path) => {
    const original = new URL(path, new URL('src/' + name, root));
    const rel = original.pathname.slice(new URL('src/', root).pathname.length);
    const local = ['images.ts','transcription.ts','speech.ts','speech-api.ts','voice-providers/tts.ts','voice-providers/tts-chain.ts'].includes(rel);
    const typeModules = ['outbound.ts','client-sessions/state.ts','identity.ts','protocol.ts','mcp-results.ts','tool-files.ts'];
    const mapped = typeModules.includes(rel) ? depth + './types.ts' : rel === 'http.ts' ? depth + '../errors.ts' : rel === 'metrics.ts' ? depth + '../observability.ts' : local ? path : depth + '../../../../src/' + rel;
    return `${prefix}${quote}${mapped}${quote}`;
  });
  source = '// Generated by scripts/reuse-media.mjs; only host imports change.\n' + source;
  const out = new URL(name, target);
  await mkdir(new URL('./', out), { recursive: true });
  if (process.argv.includes('--check')) {
    if (await readFile(out, 'utf8') !== source) throw Error(name + ' differs from src; regenerate');
  } else await writeFile(out, source);
}
console.log('Media provider and policy sources match src/');

const metrics = await readFile(new URL('src/metrics.ts', root), 'utf8');
const policy = ('// Generated from src/metrics.ts; pure formatting and privacy classification.\n' +
  'const errorText = (error: unknown) => error instanceof Error ? error.message : String(error);\n' +
  metrics.slice(metrics.indexOf('type Unit ='), metrics.indexOf('function emit(')) +
  metrics.slice(metrics.indexOf('const CLASSES:'), metrics.indexOf('const CODE_CLASSES:'))).trimEnd() + '\n';
const metricsPath = new URL('../metrics-policy.ts', target);
if (process.argv.includes('--check')) {
 if (await readFile(metricsPath,'utf8') !== policy) throw Error('metrics policy differs');
} else await writeFile(metricsPath, policy);
