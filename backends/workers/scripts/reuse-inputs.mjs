import { readFile, writeFile } from "node:fs/promises";
const source = await readFile(new URL("../../../src/inputs.ts", import.meta.url), "utf8");
const between = (start, end) => {
  const from = source.indexOf(start), to = source.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error("Input policy extraction boundary changed");
  return source.slice(from, to);
};
const text = `// Generated by scripts/reuse-inputs.mjs from src/inputs.ts. Do not edit.\nimport { HttpError } from './errors.ts';\nimport type { Sender } from './sender.ts';\nimport { compile } from '@earendil-works/pi-schema';\nconst schemaAccepts = (schema: object, value: unknown) => compile(schema).check(value);\ntype Sealed = object;\n` +
  between('export type InputKind', 'type Sealer') +
  between("export const INPUT_LIMITS", "const FINAL:") +
  between("const clip =", "/** A person's name") +
  between("/** A person's name", "/**\n * The inputs a tool's") +
  between("export function inputRequests", "const row =") +
  source.slice(source.indexOf("/** When an input expires:"));
const destination = new URL("../src/input-policy.ts", import.meta.url);
const normalized = text.trimEnd() + "\n";
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== normalized) throw new Error("Input policy drifted; regenerate");
} else await writeFile(destination, normalized);
console.log("Human input policy matches src/inputs.ts");
