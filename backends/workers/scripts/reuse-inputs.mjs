import { readFile, writeFile } from "node:fs/promises";
const source = await readFile(new URL("../../../src/inputs.ts", import.meta.url), "utf8");
const between = (start, end) => {
  const from = source.indexOf(start), to = source.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error("Input policy extraction boundary changed");
  return source.slice(from, to);
};
const text = `// Generated by scripts/reuse-inputs.mjs from src/inputs.ts. Do not edit.\nimport { HttpError } from './errors.ts';\nimport { compile } from '@earendil-works/pi-schema';\nconst schemaAccepts = (schema: object, value: unknown) => compile(schema).check(value);\ntype InputKind = 'question' | 'approval' | 'form' | 'url';\ntype Action = 'accept' | 'decline' | 'cancel';\ntype Input = { kind: InputKind; detail: Record<string, any> };\n` +
  between("export const INPUT_LIMITS", "const FINAL:") +
  between("const clip =", "/** A person's name") +
  between("export function inputRequests", "/**\n * Whether a responder");
const destination = new URL("../src/input-policy.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== text) throw new Error("Input policy drifted; regenerate");
} else await writeFile(destination, text);
console.log("Human input policy matches src/inputs.ts");
