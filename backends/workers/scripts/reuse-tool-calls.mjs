import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../../../src/tool-servers.ts', import.meta.url), 'utf8');
const start = source.indexOf('export function toolCallKey(');
const end = source.indexOf('/** An MCP `notifications/progress`', start);
if (start < 0 || end < 0) throw new Error('Tool call policy extraction boundary changed');
const text = `// Generated by scripts/reuse-tool-calls.mjs from src/tool-servers.ts. Do not edit.\nimport { createHash } from 'node:crypto';\ntype ToolCall = { toolCallId?: string; innerCallId?: string; idempotencyKey?: string; origin?: Record<string, unknown>; actor?: string };\n${source.slice(start, end)}`;
const target = new URL('../src/tool-call-policy.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== text) throw new Error('Tool call policy drifted');
} else await writeFile(target, text);
console.log('Tool call metadata and deadlines match src/tool-servers.ts');
