import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../../../src/tool-servers.ts', import.meta.url), 'utf8');
const start = source.indexOf('export function toolCallKey(');
const end = source.indexOf('/** An MCP `notifications/progress`', start);
if (start < 0 || end < 0) throw new Error('Tool call policy extraction boundary changed');
const text = `// Generated by scripts/reuse-tool-calls.mjs from src/tool-servers.ts. Do not edit.\nimport { createHash } from 'node:crypto';\ntype ToolCall = { toolCallId?: string; innerCallId?: string; idempotencyKey?: string; origin?: Record<string, unknown>; actor?: string };\n${source.slice(start, end)}`;
const approvals = await readFile(new URL('../../../src/tool-sources.ts', import.meta.url), 'utf8');
const a = approvals.indexOf('function approvalFor('), b = approvals.indexOf('/** Approval changes the call policy', a);
if (a < 0 || b < 0) throw new Error('Approval policy extraction boundary changed');
const approvalPolicy = `\ntype ApprovalMode = 'never' | 'always' | 'destructive' | 'judged';\ntype ApprovalPolicy = { default?: ApprovalMode; tools?: Record<string, 'never' | 'always' | 'judged'>; methods?: string[] };\n` + approvals.slice(a, b).replace('function approvalFor(', 'export function approvalFor(');
const combined = text + approvalPolicy;
const target = new URL('../src/tool-call-policy.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== combined) throw new Error('Tool call policy drifted');
} else await writeFile(target, combined);
console.log('Tool call metadata and deadlines match src/tool-servers.ts');
