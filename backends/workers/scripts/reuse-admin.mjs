import { mkdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../../../", import.meta.url);
const target = new URL("../src/admin/", import.meta.url);
const modules = ["accounts", "acquisition", "growth", "health", "mcp", "revenue", "signals", "stats", "usage"];
await mkdir(target, { recursive: true });
for (const name of modules) {
  const file = `admin-${name}.ts`;
  let source = await readFile(new URL(`src/${file}`, root), "utf8");
  // Only host imports change. All dashboard SQL, redaction, dates and figures remain in src/.
  source = source.replace(/(from\s+)["']\.\/db\.ts["']/g, '$1"../postgres.ts"');
  for (const dependency of ["mcp-client-kind", "signup-source"]) {
    source = source.replaceAll(`"./${dependency}.ts"`, `"../../../../src/${dependency}.ts"`);
  }
  source = "// Generated by scripts/reuse-admin.mjs; only host imports change.\n" + source;
  const out = new URL(file, target);
  if (process.argv.includes("--check")) {
    if (await readFile(out, "utf8") !== source) throw new Error(`${file} differs from src; regenerate`);
  } else await writeFile(out, source);
}
console.log("Admin read-only SQL and policy match src/");
