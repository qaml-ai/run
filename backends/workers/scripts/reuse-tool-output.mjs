import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../../../src/agent-host.ts', import.meta.url), 'utf8');
const between = (start, end) => {
  const a = source.indexOf(start), b = source.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error('Tool output policy extraction boundary changed');
  return source.slice(a, b);
};
const capped = between('  async function capped(toolCallId:', '  /** Save large results');
const details = between('  async function cappedDetails(', '  /**\n   * Bytes of the results');
const text = `// Generated by scripts/reuse-tool-output.mjs from src/agent-host.ts. Do not edit.\nimport { Buffer } from 'node:buffer';\nimport { SANDBOX_LIMITS, FILE_LIMITS } from '../../../src/limits.ts';\nimport { AGENT_UPDATES } from './sender-markers.ts';\nexport function toolOutputPolicy(config: { fileTools?: boolean; id?: string }, saveToolResult: (call: string, text: string, extension?: string) => Promise<string | undefined>) {\n${capped}${details}  return { capped, cappedDetails };\n}\n`;
const target = new URL('../src/tool-output-policy.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== text) throw new Error('Tool output policy drifted');
} else await writeFile(target, text);
console.log('Tool output caps match src/agent-host.ts');
