import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../../../", import.meta.url);
const source = await readFile(new URL("src/client-sessions/spend.ts", root), "utf8");
const sessions = await readFile(new URL("src/client-sessions.ts", root), "utf8");
const state = await readFile(new URL("src/client-sessions/state.ts", root), "utf8");
const between = (text, start, end) => {
  const first = text.indexOf(start), last = text.indexOf(end, first);
  if (first < 0 || last < 0) throw new Error(`Missing source boundary: ${start}`);
  return text.slice(first, last);
};
const sql = {};
for (const [name, prefix] of Object.entries({
  clear: "delete from agent_spend_limits where agent = $1",
  set: "insert into agent_spend_limits (agent, usd, spent, set_at)",
  read: "select usd, spent, set_at from agent_spend_limits where agent = $1",
  write: "update agent_spend_limits set spent = spent + $2 where agent = $1 and set_at = $3",
})) {
  const statement = [...sessions.matchAll(/(?:query\()"([^"]+)"/g)].map(match => match[1]).find(statement => statement.startsWith(prefix));
  if (!statement) throw new Error(`Missing source SQL: ${name}`);
  sql[name] = statement;
}
const output = `// Generated by scripts/reuse-spend-policy.mjs from the ECS runtime. Do not edit.
import { HttpError } from "./errors.ts";
${state.match(/^export type SpendLimit = .+;$/m)?.[0] ?? (() => { throw new Error("Missing SpendLimit"); })()}
${between(source, "/** `spendLimit` as given:", "/** How long an end user's charge")}
${source.match(/^export const dollars = .+;$/m)?.[0] ?? (() => { throw new Error("Missing dollars"); })()}
${between(sessions, "  private async agentSpendLimit(session: Session): Promise<string | undefined> {", "  /** The agent's spend limit, read once per load;")
  .replace("  private async agentSpendLimit(session: Session): Promise<string | undefined> {", "export function agentSpendMessage(id: string, spend: SpendLimit | null): string | undefined {")
  .replace("    const spend = await this.spendOf(session);\n", "")
  .replace("${session.header.id}", "${id}")}
export const AGENT_SPEND_SQL = ${JSON.stringify(sql, null, 2)};
`;
const target = new URL("../src/agent-spend-policy.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== output) throw new Error("Agent spend policy has source drift");
} else await writeFile(target, output);
console.log("Agent spend policy and SQL match src/");
