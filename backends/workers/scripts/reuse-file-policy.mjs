import { readFile, writeFile } from "node:fs/promises";
const source = await readFile(
  new URL("../../../src/volumes.ts", import.meta.url),
  "utf8",
);
const take = (from, to) => {
  const start = source.indexOf(from),
    end = source.indexOf(to, start);
  if (start < 0 || end < 0)
    throw new Error(`File policy extraction boundary changed: ${from}`);
  return source.slice(start, end);
};
const files = await readFile(
  new URL("../../../src/files.ts", import.meta.url),
  "utf8",
);
const segment = (from, to) => {
  const start = files.indexOf(from),
    end = to ? files.indexOf(to, start) : files.length;
  if (start < 0 || end < 0)
    throw new Error("File policy extraction boundary changed");
  return files.slice(start, end);
};
const fileText =
  "// Generated by scripts/reuse-file-policy.mjs from Node file helpers. Do not edit.\n" +
  'import { Buffer } from "node:buffer";\nimport { TextDecoder } from "node:util";\nimport { createHmac, timingSafeEqual } from "node:crypto";\nimport { HttpError } from "./errors.ts";\nimport { FILE_LIMITS } from "../../../src/limits.ts";\n' +
  segment("export const essence", "/** A file's download:") +
  segment("export function safeName", "/** What an inline image") +
  `export const MOUNT_LIMIT = ${take("export const VOLUME_LIMITS", "/** A snapshot's labels:").match(/mounts: (\d+)/)[1]};\n` +
  take("export function normalizePath", "const parentOf") +
  segment("export type LinkGrant")
    .replace("volume: string; ", "")
    .replace("one volume file", "one file")
    .replace("tenant, volume, path", "tenant, path");
const filePath = new URL("../src/file-policy.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(filePath, "utf8")) !== fileText)
    throw new Error("File policy differs from src; regenerate");
} else await writeFile(filePath, fileText);
