import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../../../src/client-sessions/spend.ts', import.meta.url), 'utf8');
const generated = '// Generated by scripts/reuse-run-caps.mjs from src/client-sessions/spend.ts. Do not edit.\n' +
  "import type { RunLimits } from './model-policy.ts';\n" +
  source.slice(source.indexOf('export const RUN_LIMITS:'), source.indexOf('/** A model response\'s cost'));
const output = new URL('../src/run-caps-policy.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== generated) throw new Error('Workers run caps drifted from src');
} else await writeFile(output, generated);
