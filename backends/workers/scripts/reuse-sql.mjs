import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const billing = await readFile(
  resolve(here, "../../../src/billing.ts"),
  "utf8",
);
const start = billing.indexOf("export async function postLedger(");
const end = billing.indexOf("export interface BillingOptions", start);
if (start < 0 || end < 0)
  throw new Error("Billing extraction boundary changed");
const spendable = billing.slice(
  billing.indexOf("  async spendable("),
  billing.indexOf(
    "  /** Whether a prepaid tenant",
    billing.indexOf("  async spendable("),
  ),
);
const text =
  `// Generated by scripts/reuse-sql.mjs. Exact pure SQL functions from src/billing.ts.\n// Do not edit; regenerate and run --check when the source changes.\nimport type { Sql } from './postgres.ts';\nimport { DEFAULT_PRICING } from '../../../src/pricing.ts';\nexport type LedgerKind = 'grant' | 'purchase' | 'usage' | 'storage' | 'adjustment' | 'refund';\nexport const LEDGER_KINDS: LedgerKind[] = ['grant', 'purchase', 'usage', 'storage', 'adjustment', 'refund'];\nexport interface LedgerEntry { tenant: string; kind: LedgerKind; amount: number; key: string; metadata?: Record<string, unknown> }\nexport interface UsageCharge { tenant: string; amount: number; metadata: Record<string, number> }\nconst HOUR = 3_600_000, MINUTE = 60_000;\n\n` +
  billing.slice(start, end) +
  `\nexport class BillingSpendable {\n  readonly pricing = DEFAULT_PRICING;\n  readonly options: { pending?: (tenant: string) => number } = {};\n${spendable}}\n`;
let endUsers = await readFile(
  resolve(here, "../../../src/end-user-credits.ts"),
  "utf8",
);
endUsers =
  "// Generated from src/end-user-credits.ts; only infrastructure imports replaced.\n" +
  endUsers
    .replace('"./db.ts"', '"./postgres.ts"')
    .replace('"./http.ts"', '"./errors.ts"');
for (const [name, expected] of [
  ["billing-sql.ts", text],
  ["end-user-credits.ts", endUsers],
]) {
  const path = resolve(here, "../src", name);
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")) !== expected)
      throw new Error(`${name} differs from source; regenerate`);
  } else await writeFile(path, expected);
}
console.log("Reused billing SQL and end-user credit policy match src/");
