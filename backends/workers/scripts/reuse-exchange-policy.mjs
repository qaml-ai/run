import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../../../", import.meta.url);
const source = await readFile(new URL("src/credential-exchange.ts", root), "utf8");
const from = source.indexOf("export const EXCHANGE_LIMITS"), to = source.indexOf("type Entry =", from);
const output = ("// Generated by scripts/reuse-exchange-policy.mjs from src/credential-exchange.ts. Do not edit.\n" + source.slice(from, to).replace("const TOKEN =", "export const TOKEN =")).trimEnd() + "\n";
const file = new URL("../src/exchange-policy.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (await readFile(file, "utf8") !== output) throw new Error("Exchange policy drift; run node scripts/reuse-exchange-policy.mjs");
} else await writeFile(file, output);
