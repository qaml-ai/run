import { diverge } from './repo-divergence.mjs';
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../../../', import.meta.url);
const files = await readFile(new URL('src/files.ts', root), 'utf8');
const tools = await readFile(new URL('src/client-sessions/tools.ts', root), 'utf8');
const inspect = await readFile(new URL('src/inspect.ts', root), 'utf8');
let policy = files.slice(files.indexOf('export type FileTranscript'), files.indexOf('/** What a signed link'));
// Workers histories name immutable repo versions.
const repoFiles = String.raw`/**
 * A file as the transcript keeps it, in a user message or a tool result, in place of its bytes.
 * The immutable version and blob retain the bytes after the file is changed or deleted.
 */
export type RepoFileRef = {
  type: "file"; path: string; repo: string; version: string; blob: string; repoPath?: string; size: number; contentType: string;
  media?: Media;
  /** Audio transcribed when it was attached (transcription.ts): the model reads this in place of the sound. */
  transcript?: FileTranscript;
  /** Audio that was to be transcribed by default and could not be, and why: the model is told. */
  untranscribed?: string;
  /** A text file's first lines, so the model knows its shape without reading it. */
  head?: string;
};

export type FileRef = RepoFileRef;

export function validFileRef(value: any): value is FileRef {
  return !!value && value.type === "file" && typeof value.path === "string" && typeof value.repo === "string" &&
    /^[a-f0-9]{40}$/.test(value.version) && Number.isSafeInteger(value.size) && value.size >= 0 && typeof value.contentType === "string" &&
    typeof value.blob === "string" && /^[a-f0-9]{40}$/.test(value.blob) &&
    (value.transcript === undefined || (typeof value.transcript?.text === "string" && Number.isFinite(value.transcript.seconds) && typeof value.transcript.model === "string"));
}

`;
policy = policy.slice(0, policy.indexOf('/**\n * A file as')) + repoFiles + policy.slice(policy.indexOf('/** Which native block'));
const start = tools.indexOf('  if (!Array.isArray(inputs))', tools.indexOf('export async function attach('));
const checked = tools.slice(start, tools.indexOf('  const volumes = ctx.options.volumes;', start)).replace('!ctx.options.outbound', '!canFetchURL');
const source = '// Generated by scripts/reuse-attachments.mjs from src/files.ts and src/client-sessions/tools.ts.\n' +
  'import { Buffer } from "node:buffer";\nimport type { Api, Model } from "@earendil-works/pi-ai";\nimport { FILE_LIMITS } from "../../../src/limits.ts";\nimport { HttpError } from "./errors.ts";\n' +
  policy + '\nexport function attachmentInputs(inputs: unknown, canFetchURL = true) {\n' + checked + '  return checked;\n}\n\n' +
  files.slice(files.indexOf('export const textual ='), files.indexOf('\n', files.indexOf('export const textual ='))) + '\n\n' +
  inspect.slice(inspect.indexOf('function firstLines(')).replace('function firstLines(', 'export function firstLines(');
const path = new URL('../src/attachment-policy.ts', import.meta.url);
const output = diverge('attachment-policy.ts', source);
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw new Error('Attachment policy differs from src; regenerate');
} else await writeFile(path, output);
console.log('Attachment validation and file presentation policies match src');
