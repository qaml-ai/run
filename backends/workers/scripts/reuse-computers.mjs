import { readFile, writeFile } from 'node:fs/promises';
const source = async name => readFile(new URL(`../../../src/computers/${name}.ts`, import.meta.url), 'utf8');
const service = await source('service'), providers = await source('providers'), managed = await source('managed'), microvm = await source('microvm');
const section = (text, start, end) => {
  const a = text.indexOf(start), b = text.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error(`Computer source boundary changed: ${start}`);
  return text.slice(a, b);
};
// Modal was dropped from Workers; preserve the shared tool definitions but omit that provider.
const policy = `// Generated by scripts/reuse-computers.mjs; infrastructure imports replaced and Modal omitted.\nimport { HttpError } from '../errors.ts';\ntype ToolDefinition = { name: string; description: string; timeoutMs: number; exposure: string; parameters: Record<string, unknown> };\n`
  + section(providers, 'export const PROVIDERS', '/** A provider').replace('"lambda", "modal",', '"lambda",')
  + section(providers, 'export const quote', '/** Internal file')
  + section(service, 'const parameters =', 'const publicConnection');
// Include both adjacent pure functions, without importing the Node-managed service.
const pureStart = managed.indexOf('/** A file tool');
if (pureStart < 0) throw new Error('Computer pure command boundary changed');
const pure = managed.slice(pureStart);
const result = policy + pure + '\nexport { COMMON, SHELL, BROWSER };\n';
const file = new URL('../src/computers/policy.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(file, 'utf8') !== result) throw new Error('Computer policy differs from src; regenerate');
} else await writeFile(file, result);
const microvmPolicy = ('// Generated by scripts/reuse-computers.mjs from src/computers/microvm.ts.\n' + section(microvm, 'export const MICROVM_MAX_SECONDS', 'export type MicrovmSettings') + section(microvm, 'const paths:', '// The local AWS service').replace('const paths:', 'export const paths:') + section(microvm, 'export type Observation', 'export function microvmMachines')).trimEnd() + '\n';
const microvmFile = new URL('../src/computers/microvm-policy.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(microvmFile, 'utf8') !== microvmPolicy) throw new Error('MicroVM policy differs from src; regenerate');
} else await writeFile(microvmFile, microvmPolicy);
console.log('Reused computer tools and command policy match src/');
