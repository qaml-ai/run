// Assemble the review document; --check refuses drift without changing files.
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const docs = new URL('../docs/', import.meta.url);
const read = name => readFile(new URL(name, docs), 'utf8');
const sections = [
  ['hybrid-tables.md', '1. Table map and transaction seams'],
  ['hybrid-code.md', '2. Code removed and newly required'],
  ['hybrid-hyperdrive.md', '3. Hyperdrive and real-schema credit transactions'],
  ['hybrid-images.md', '4. Images and isolate memory'],
];
let result = '<!-- Generated by studies/build-hybrid.mjs from hybrid-*.md sections. -->\n\n';
result += (await read('hybrid-overview.md')).trim() + '\n\n';
for (const [name, title] of sections) {
  const content = (await read(name)).trim().replace(/^# .+\n/, `## ${title}\n`)
    .replace(/^(#{2,5}) /gm, '$1# ');
  // The section heading is level two; only its subheadings are demoted.
  result += content.replace(/^### /, '## ') + '\n\n';
}
result += (await read('hybrid-verdict.md')).trim() + '\n';
if (process.argv.includes('--check')) {
  assert.equal(await read('HYBRID.md'), result, 'Run node backends/cloudflare/studies/build-hybrid.mjs');
  console.log('HYBRID.md matches all source sections');
} else {
  await writeFile(new URL('HYBRID.md', docs), result);
  console.log('Wrote HYBRID.md');
}
