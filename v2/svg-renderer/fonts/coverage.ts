function supports(character: string): boolean {
  const point = character.codePointAt(0)!;
  let low = 0, high = coverage.length;
  while (low < high) {
    const index = (low + high) >>> 1;
    const [first, last] = coverage[index]!;
    if (point < first!) high = index;
    else if (point > last!) low = index + 1;
    else return true;
  }
  return false;
}

export function normalizeMissingGlyphs(text: string): string {
  return Array.from(text, character => {
    if (supports(character)) return character;
    const normalized = character.normalize("NFKC");
    return normalized !== character && Array.from(normalized).every(supports) ? normalized : character;
  }).join("");
}
