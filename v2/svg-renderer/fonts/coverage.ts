const ON_DEMAND_IDS: readonly OnDemandScriptId[] = ["cjk-sc", "cjk-kr"];

function inRanges(point: number, ranges: RangeList): boolean {
  let low = 0, high = ranges.length;
  while (low < high) {
    const index = (low + high) >>> 1;
    const [first, last] = ranges[index]!;
    if (point < first) high = index;
    else if (point > last) low = index + 1;
    else return true;
  }
  return false;
}

function isPreservedFormat(point: number): boolean {
  return point === 0x09 || point === 0x0a || point === 0x0d ||
    point === 0x200c || point === 0x200d || point === 0xfe0e || point === 0xfe0f;
}

function classifyPoint(
  point: number,
  bundled: Set<BundledExtraScriptId>,
  onDemand: Set<OnDemandScriptId>,
): void {
  // Fast path: ASCII, Latin, Greek, and Cyrillic (< 0x591) are covered by base Noto Sans/Serif/Mono.
  if (point < 0x591 || inRanges(point, baseCoverage)) return;
  for (const [id, ranges] of bundledExtraRanges) {
    if (inRanges(point, ranges)) {
      bundled.add(id);
      return;
    }
  }
  for (const id of ON_DEMAND_IDS) {
    if (inRanges(point, onDemandRanges[id])) {
      onDemand.add(id);
      return;
    }
  }
}

/**
 * Detects which optional bundled or on-demand script fonts are needed by an SVG or text string.
 * Latin, Greek, Cyrillic, Math, Symbols, Symbols2, and Emoji return empty sets (zero overhead).
 */
export function detectExtraScripts(input: string): {
  bundled: BundledExtraScriptId[];
  onDemand: OnDemandScriptId[];
} {
  const bundled = new Set<BundledExtraScriptId>();
  const onDemand = new Set<OnDemandScriptId>();

  for (let i = 0; i < input.length; i++) {
    const point = input.codePointAt(i)!;
    if (point > 0xffff) i++;
    classifyPoint(point, bundled, onDemand);
  }

  // Also check XML numeric character references (e.g. &#x674E; or &#26446;).
  if (input.includes("&#")) {
    for (const match of input.matchAll(/&#(?:x([0-9a-fA-F]{1,6})|(\d{1,7}));/g)) {
      const point = match[1] ? Number.parseInt(match[1], 16) : Number.parseInt(match[2]!, 10);
      if (Number.isInteger(point) && point >= 0x591 && point <= 0x10ffff) {
        classifyPoint(point, bundled, onDemand);
      }
    }
  }

  return { bundled: [...bundled], onDemand: [...onDemand] };
}

export function supportsCodepoint(character: string, loadedOnDemand?: ReadonlySet<OnDemandScriptId>): boolean {
  const point = character.codePointAt(0)!;
  if (isPreservedFormat(point)) return true;
  if (inRanges(point, baseCoverage)) return true;
  for (const [, ranges] of bundledExtraRanges) {
    if (inRanges(point, ranges)) return true;
  }
  if (loadedOnDemand && loadedOnDemand.size > 0) {
    for (const id of loadedOnDemand) {
      if (inRanges(point, onDemandRanges[id])) return true;
    }
  }
  return false;
}

/**
 * Ensures resvg 2.6.2 never stalls mid-run font fallback or emits tofu boxes for emoji/combining sequences:
 * 1. Normalizes to NFC first so decomposed combining accents (e.g. e + U+0301) render as precomposed glyphs.
 * 2. Drops emoji skin-tone modifiers (U+1F3FB–U+1F3FF), keycap combining marks (U+20E3), and tag
 *    characters (U+E0020–U+E007F) that render as empty boxes in resvg/NotoEmoji.
 * 3. Replaces ZWJ (U+200D) inside emoji sequences with ZWNJ (U+200C) (preserving Indic/Arabic ZWJ shaping)
 *    and inserts ZWNJ between adjacent Regional Indicators (U+1F1E6–U+1F1FF) so ZWJ emoji sequences and
 *    flags draw their component glyphs instead of tofu boxes.
 * 4. Replaces uncovered characters with their NFKC compatibility decomposition (keeping supported
 *    chars and substituting any remaining unsupported printable chars with "?") while preserving
 *    safe whitespace/joiner/variation characters and any bundled or loaded on-demand script fonts.
 * 5. Breaks f+f / f+i / f+l ligatures with U+200C (ZWNJ) so Noto Sans/Serif ligature shaping
 *    cannot stall glyph fallback for trailing math/emoji runs.
 */
export function normalizeMissingGlyphs(text: string, loadedOnDemand?: ReadonlySet<OnDemandScriptId>): string {
  const preprocessed = text
    .normalize("NFC")
    .replace(/[\u{1F3FB}-\u{1F3FF}\u20E3\u{E0020}-\u{E007F}]/gu, "")
    .replace(/(?<=[\p{Extended_Pictographic}\uFE0F])\u200d|\u200d(?=[\p{Extended_Pictographic}\uFE0F])/gu, "\u200c")
    .replace(/([\u{1F1E6}-\u{1F1FF}])(?=[\u{1F1E6}-\u{1F1FF}])/gu, "$1\u200c");
  const safe = Array.from(preprocessed, character => {
    if (supportsCodepoint(character, loadedOnDemand)) return character;
    const normalized = character.normalize("NFKC");
    if (normalized !== character) {
      return Array.from(normalized, part => supportsCodepoint(part, loadedOnDemand) ? part : "?").join("");
    }
    return "?";
  }).join("");
  return safe.replace(/f(?=[fil])/g, "f\u200c");
}
