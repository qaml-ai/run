"""Validate installed wheel files before reusing a Python dependency cache."""
import base64
import csv
import hashlib
from pathlib import Path
import sys


def validate(cache):
    cache = Path(cache)
    sites = list(cache.glob("lib/python*/site-packages"))
    if len(sites) != 1:
        return ["Python cache has no unique site-packages directory"]
    site = sites[0]
    records = sorted(site.glob("*.dist-info/RECORD"))
    if not records:
        return ["Python cache has no installed wheel records"]
    errors = []
    checked = 0
    for record in records:
        try:
            with record.open(newline="") as stream:
                for name, expected, size in csv.reader(stream):
                    if not expected:
                        continue  # RECORD itself and generated bytecode have no hash.
                    target = site / name
                    if not target.resolve().is_relative_to(cache.resolve()):
                        errors.append(f"Wheel record has a path outside the cache: {record.relative_to(cache)}")
                        continue
                    label = target.relative_to(cache)
                    if not target.is_file():
                        errors.append(f"Missing wheel file: {label}")
                        continue
                    actual_size = target.stat().st_size
                    if size and actual_size != int(size):
                        errors.append(f"Wheel size mismatch: {label} (expected {size}, found {actual_size} bytes)")
                        continue
                    algorithm, encoded = expected.split("=", 1)
                    with target.open("rb") as stream:
                        digest = hashlib.file_digest(stream, algorithm).digest()
                    if base64.urlsafe_b64encode(digest).decode().rstrip("=") != encoded:
                        errors.append(f"Wheel hash mismatch: {label} ({actual_size} bytes)")
                    checked += 1
        except (OSError, ValueError, csv.Error):
            errors.append(f"Cannot validate wheel record: {record.relative_to(cache)}")
    if not checked and not errors:
        errors.append("Python cache has no hashed wheel files")
    return errors


if __name__ == "__main__":
    errors = validate(sys.argv[1])
    for error in errors:
        print(error, file=sys.stderr)
    raise SystemExit(bool(errors))
